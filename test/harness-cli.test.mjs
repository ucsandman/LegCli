// `leg harness` through the real CLI in a subprocess: exit codes, JSON
// shapes, the first run's refusal to write without consent, and the
// read-only verbs writing nothing. Every run points LEG_HARNESS_HOME at a
// throwaway directory (test/helpers.mjs testEnv), never the real home.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { makeHome, testEnv, leg, legFail } from './helpers.mjs'
import { buildClaudeHome, buildCodexHome, buildAgyHome, CANARY, fakeToken } from './harness-fixture.mjs'

function setup({ codex = true, claude = true, agy = false } = {}) {
  const home = makeHome()
  if (claude) buildClaudeHome(home)
  if (codex) buildCodexHome(home)
  if (agy) buildAgyHome(home)
  return { home, env: testEnv(home) }
}
const snapshot = (home) => ({ agents: readFileSync(join(home, '.codex', 'AGENTS.md'), 'utf8'), toml: readFileSync(join(home, '.codex', 'config.toml'), 'utf8') })

test('help, status off, and every read-only verb before enabling: nothing written, exit codes say why', () => {
  const { home, env } = setup()
  const before = snapshot(home)
  assert.match(leg(['harness'], env), /leg harness: carry the source agent's working environment/)
  assert.match(leg(['harness', 'help'], env), /status \[--json\]/)
  const status = leg(['harness', 'status'], env)
  assert.match(status, /portable harness: off/)
  assert.match(status, /source: claude \(on this machine: claude, codex\)/)
  assert.match(status, /grok: unsupported/)
  const j = JSON.parse(leg(['harness', 'status', '--json'], env))
  assert.equal(j.enabled, false); assert.equal(j.policy, 'off'); assert.equal(j.captured, false)
  assert.deepEqual(j.sources_detected, ['claude', 'codex'])
  assert.equal(legFail(['harness', 'inspect'], env).status, 3)
  assert.equal(legFail(['harness', 'explain'], env).status, 3, 'explain before a capture: nothing to explain')
  assert.equal(legFail(['harness', 'bogus'], env).status, 2)
  assert.equal(legFail(['harness', 'policy', 'loose'], env).status, 2)
  assert.equal(legFail(['harness', 'source', 'grok'], env).status, 2)
  assert.equal(legFail(['harness', 'diff'], env).status, 2)
  const doctor = legFail(['harness', 'doctor'], env)
  assert.equal(doctor.status, 0, doctor.stdout)
  assert.match(doctor.stdout, /engine\s+ok\s+vendored Agnostic AI engine/)
  assert.match(doctor.stdout, /enabled\s+note\s+off/)
  assert.deepEqual(snapshot(home), before, 'no read-only verb touched a client')
  assert.ok(!existsSync(join(home, 'harness')), 'and no state directory appeared')
})

test('sync on an install that never enabled the harness writes nothing and names the consent step; check and diff still report', () => {
  const { home, env } = setup()
  const before = snapshot(home)
  const r = legFail(['harness', 'sync'], env)
  assert.equal(r.status, 3, r.stdout + r.stderr)
  assert.match(r.stderr, /portable harness is off: leg harness enable/)
  assert.deepEqual(snapshot(home), before)
  assert.ok(!existsSync(join(home, 'harness', 'harness-state.json')), 'no ownership record was created')
  assert.equal(legFail(['harness', 'check'], env).status, 1, 'check still reports the stale destination')
  assert.deepEqual(snapshot(home), before, 'and writes nothing')
  assert.equal(legFail(['harness', 'sync', '--dry-run'], env).status, 1)
  assert.deepEqual(snapshot(home), before)
})

test('enable without --yes and without a terminal shows the plan and writes nothing (exit 3); with --yes it captures, applies and records consent', () => {
  const { home, env } = setup()
  const before = snapshot(home)
  const dry = legFail(['harness', 'enable'], env)
  assert.equal(dry.status, 3, dry.stdout + dry.stderr)
  assert.match(dry.stdout, /captured claude: rules 1, identity 1, hooks 6, skills 3, agents 2, commands 1, mcp 3, permissions 4/)
  assert.match(dry.stdout, /Codex CLI\s+stale/)
  assert.match(dry.stdout, /not carried:/)
  assert.match(dry.stdout, /skill beta: a real directory already lives/)
  assert.match(dry.stdout, /nothing written\. Re-run with --yes/)
  assert.match(dry.stdout, /CONTEXT7_API_KEY looks like a secret/)
  assert.deepEqual(snapshot(home), before, 'the plan wrote nothing')
  assert.equal(JSON.parse(leg(['harness', 'status', '--json'], env)).enabled, false)

  const on = leg(['harness', 'enable', '--yes', '--policy', 'warn'], env)
  assert.match(on, /portable harness on: source claude, policy warn; wrote \d+ file\(s\)/)
  const prefs = JSON.parse(readFileSync(join(home, 'preferences.json'), 'utf8'))
  assert.deepEqual(prefs.harness, { enabled: true, policy: 'warn', source: 'claude' })
  const after = snapshot(home)
  assert.match(after.agents, /GENERATED by Leg harness/)
  assert.match(after.agents, /Batch tool calls/)
  assert.match(after.toml, /\[mcp_servers\.existing\]/)
  assert.match(after.toml, /# >>> leg harness hooks start/)
  assert.ok(!after.toml.includes(fakeToken('a')) && !after.toml.includes(CANARY.claude), 'no credential reached a client')
  assert.equal(legFail(['harness', 'check'], env).status, 0, 'a fresh apply is in sync')
  const s = JSON.parse(leg(['harness', 'status', '--json'], env))
  assert.equal(s.enabled, true); assert.equal(s.policy, 'warn'); assert.equal(s.captured, true)
  assert.ok(['synced', 'partial'].includes(s.targets.codex.state))
  assert.equal(s.targets.claude.state, 'source')
  assert.equal(s.targets.codex.components.skills.carried, 2)
  assert.equal(s.targets.codex.components.skills.total, 3)
})

test('check exits 1 on drift, sync repairs it and exits 0, a hand edit is refused (exit 1) and named, --force replaces it with a backup', () => {
  const { home, env } = setup()
  leg(['harness', 'enable', '--yes'], env)
  // source drifts
  writeFileSync(join(home, '.claude', 'CLAUDE.md'), readFileSync(join(home, '.claude', 'CLAUDE.md'), 'utf8') + '\n- A newer rule.\n')
  const chk = legFail(['harness', 'check'], env)
  assert.equal(chk.status, 1, chk.stdout)
  assert.match(chk.stdout, /captured claude/)
  assert.match(chk.stdout, /Codex CLI\s+stale/)
  assert.doesNotMatch(readFileSync(join(home, '.codex', 'AGENTS.md'), 'utf8'), /A newer rule/, 'check wrote nothing')
  const sync = legFail(['harness', 'sync'], env)
  assert.equal(sync.status, 0, sync.stdout)
  assert.match(sync.stdout, /1 file\(s\) written/)
  assert.match(readFileSync(join(home, '.codex', 'AGENTS.md'), 'utf8'), /A newer rule/)
  assert.equal(legFail(['harness', 'check'], env).status, 0)
  // a hand edit
  const f = join(home, '.codex', 'AGENTS.md')
  writeFileSync(f, readFileSync(f, 'utf8').split('\n').filter((l) => !l.includes('GENERATED by Leg harness')).join('\n') + '\nmine\n')
  const refused = legFail(['harness', 'sync'], env)
  assert.equal(refused.status, 1)
  assert.match(refused.stdout, /Codex CLI\s+attention/)
  assert.match(refused.stdout, /hand-edited since Leg last wrote it; left alone \(backup taken\)/)
  assert.match(readFileSync(f, 'utf8'), /\nmine\n/, 'the hand edit survived')
  const forced = legFail(['harness', 'sync', '--force', '--to', 'codex'], env)
  assert.equal(forced.status, 0, forced.stdout)
  assert.match(readFileSync(f, 'utf8'), /GENERATED by Leg harness/)
  const hist = JSON.parse(leg(['harness', 'history', '--json'], env))
  assert.ok(hist.some((r) => r.op === 'apply' && r.force === true && r.target === 'codex'))
  assert.ok(hist.some((r) => r.op === 'apply' && r.backups.length > 0), 'a backup is on record')
  const explain = leg(['harness', 'explain'], env)
  assert.match(explain, /codex\s+mcp\s+mcp events: Codex has no SSE transport/)
  assert.match(explain, /grok\s+everything/)
  const diff = leg(['harness', 'diff', 'codex'], env)
  assert.match(diff, /already in sync/)
})

test('policy, source and disable round-trip through preferences; JSON sync report names every client and component', () => {
  const { home, env } = setup({ agy: true })
  leg(['harness', 'enable', '--yes', '--source', 'claude', '--policy', 'sync'], env)
  assert.match(leg(['harness', 'policy', 'strict'], env), /harness policy: strict/)
  assert.match(leg(['harness', 'source', 'codex'], env), /harness source: codex/)
  const prefs = JSON.parse(readFileSync(join(home, 'preferences.json'), 'utf8'))
  assert.deepEqual(prefs.harness, { enabled: true, policy: 'strict', source: 'codex' })
  leg(['harness', 'source', 'claude'], env)
  const r = JSON.parse(leg(['harness', 'sync', '--json'], env))
  assert.deepEqual(Object.keys(r.targets), ['claude', 'codex', 'gemini', 'agy'])
  assert.equal(r.targets.claude.state, 'source')
  for (const id of ['codex', 'gemini', 'agy']) assert.ok(['synced', 'partial'].includes(r.targets[id].state), `${id}: ${r.targets[id].state}`)
  assert.equal(r.targets.agy.components.permissions.state, 'unsupported')
  assert.equal(r.targets.gemini.components.agents.state, 'unsupported')
  const off = leg(['harness', 'disable'], env)
  assert.match(off, /portable harness off/)
  assert.equal(JSON.parse(readFileSync(join(home, 'preferences.json'), 'utf8')).harness.enabled, false)
  assert.match(readFileSync(join(home, '.codex', 'AGENTS.md'), 'utf8'), /GENERATED by Leg harness/, 'disable removes nothing')
  assert.match(leg(['harness', 'status'], env), /portable harness: off/)
})

test('no source on the machine: enable and sync fail with exit 3 and a named remedy; doctor reports the missing source', () => {
  const { env } = setup({ claude: false, codex: false })
  const e = legFail(['harness', 'enable', '--yes'], env)
  assert.equal(e.status, 3); assert.match(e.stderr, /no source client found/)
  const s = legFail(['harness', 'sync'], env)
  assert.equal(s.status, 3); assert.match(s.stderr, /leg harness source <claude\|codex>/)
  const d = legFail(['harness', 'doctor'], env)
  assert.equal(d.status, 1); assert.match(d.stdout, /source\s+FAIL/)
})
