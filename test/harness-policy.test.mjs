test('a hand-edited managed file is backed up and left alone: sync reports attention and proceeds, strict refuses', () => {
  const dir = fresh()
  h.setHarnessConfig({ enabled: true, policy: 'sync', source: 'claude' })
  h.prepareHarnessForHandoff({ from: 'claude', to: 'codex' })
  const edited = readFileSync(agentsMd(dir), 'utf8').split('\n').filter((l) => !l.includes('GENERATED by Leg harness')).join('\n') + '\nMy own line.\n'
  writeFileSync(agentsMd(dir), edited)
  const p = h.prepareHarnessForHandoff({ from: 'claude', to: 'codex', sessionId: 's-edit' })
  assert.equal(p.state, 'attention'); assert.equal(p.proceed, true)
  assert.equal(readFileSync(agentsMd(dir), 'utf8'), edited, 'the hand edit survives')
  assert.ok(p.attention.some((a) => a.component === 'rules' && /hand-edited/.test(a.reason)))
  const backups = readdirSync(join(process.env.LEG_HOME, 'harness', 'backups'))
  assert.ok(backups.some((n) => n.startsWith('codex-AGENTS.md')), `a backup exists: ${backups.join(', ')}`)
  // two backups by now: the fixture's original from the first write, and the hand-edited text from the refusal
  assert.ok(backups.filter((n) => n.startsWith('codex-AGENTS.md')).some((n) => readFileSync(join(process.env.LEG_HOME, 'harness', 'backups', n), 'utf8').includes('My own line.')), 'the hand-edited text was backed up')
  h.setHarnessConfig({ policy: 'strict' })
  const s = h.prepareHarnessForHandoff({ from: 'claude', to: 'codex', sessionId: 's-strict' })
  assert.equal(s.state, 'blocked'); assert.equal(s.proceed, false)
  assert.match(s.reason, /strict policy: codex is attention/)
  assert.equal(readFileSync(agentsMd(dir), 'utf8'), edited, 'strict never forces')
  // --force replaces it; the hand-edited text was backed up once, at first detection, and that backup is what survives the overwrite
  const forced = h.applyHarness({ to: 'codex', force: true })
  assert.equal(forced.targets.codex.files_written, 1)
  const kept = readdirSync(join(process.env.LEG_HOME, 'harness', 'backups')).filter((n) => n.startsWith('codex-AGENTS.md')).map((n) => readFileSync(join(process.env.LEG_HOME, 'harness', 'backups', n), 'utf8'))
  assert.ok(kept.some((t) => t.includes('My own line.')), 'the overwritten hand edit is recoverable from a backup')
  assert.match(readFileSync(agentsMd(dir), 'utf8'), /GENERATED by Leg harness/)
  const s2 = h.prepareHarnessForHandoff({ from: 'claude', to: 'codex', sessionId: 's-strict2' })
  assert.equal(s2.proceed, true)
  assert.ok(h.readHistory().some((r) => r.op === 'prepare' && r.session_id === 's-strict' && r.proceed === false))
})

