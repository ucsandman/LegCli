test('the board may narrow the harness policy or turn it off, never widen it or turn it on', async () => {
  fresh()
  h.setHarnessConfig({ enabled: true, policy: 'warn', source: 'claude' })
  const { createBoardServer } = await import('../src/server.mjs')
  const server = createBoardServer({ bind: '127.0.0.1', port: 0, token: '', scheduler: false })
  const { port } = await server.start()
  const post = async (body) => { const r = await fetch(`http://127.0.0.1:${port}/api/settings`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) }); return { status: r.status, json: await r.json() } }
  try {
    assert.equal((await post({ harness: { policy: 'sync' } })).status, 400, 'warn -> sync is a widening')
    assert.equal((await post({ harness: { policy: 'strict' } })).status, 400)
    assert.equal((await post({ harness: { enabled: true } })).status, 400)
    assert.equal(h.harnessConfig().policy, 'warn')
    h.setHarnessConfig({ policy: 'strict' })
    const narrowed = await post({ harness: { policy: 'sync' } })
    assert.equal(narrowed.status, 200); assert.equal(narrowed.json.preferences.harness.policy, 'sync')
    const off = await post({ harness: { enabled: false } })
    assert.equal(off.status, 200); assert.equal(off.json.preferences.harness.enabled, false)
  } finally { await server.stop() }
})

